package generator

import (
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

func TestGenerateOutput(t *testing.T) {
	src, err := Generate("greet", Spec{FuncName: "Greet", Template: "Hello {name}, welcome to {place}!"})
	if err != nil {
		t.Fatal(err)
	}
	want := `// Code generated by qfiller. DO NOT EDIT.

package greet

import "strings"

const (
	greetLit0 = "Hello "
	greetLit1 = ", welcome to "
	greetLit2 = "!"
)

func Greet(name, place string) string {
	var b strings.Builder
	b.Grow(20 + len(name) + len(place))
	b.WriteString(greetLit0)
	b.WriteString(name)
	b.WriteString(greetLit1)
	b.WriteString(place)
	b.WriteString(greetLit2)
	return b.String()
}
`
	if string(src) != want {
		t.Errorf("got:\n%s\nwant:\n%s", src, want)
	}
}

func TestGenerateErrors(t *testing.T) {
	cases := []struct {
		pkg   string
		specs []Spec
	}{
		{"bad pkg", []Spec{{FuncName: "F", Template: "x"}}},
		{"p", []Spec{{FuncName: "1F", Template: "x"}}},
		{"p", []Spec{{FuncName: "F", Template: "x"}, {FuncName: "F", Template: "y"}}},
		{"p", []Spec{{FuncName: "F", Template: "{oops"}}},
	}
	for _, c := range cases {
		if _, err := Generate(c.pkg, c.specs...); err == nil {
			t.Errorf("Generate(%q, %v): expected error", c.pkg, c.specs)
		}
	}
}

// TestGenerateCompiles builds the generated code into a program and checks
// that every function returns the expected string.
func TestGenerateCompiles(t *testing.T) {
	if testing.Short() {
		t.Skip("runs the go tool")
	}
	src, err := Generate("main",
		Spec{FuncName: "Greet", Template: "Hello {name}, welcome to {place}!"},
		Spec{FuncName: "Empty", Template: ""},
		Spec{FuncName: "Static", Template: "no placeholders"},
		Spec{FuncName: "Only", Template: "{v}"},
		Spec{FuncName: "Repeat", Template: "{x}-{x}-{y}"},
		Spec{FuncName: "Braces", Template: `{{"{k}": "{v}"}}`},
		// Parameter named like the constant the generator would pick.
		Spec{FuncName: "Clash", Template: "a{clashLit0}b"},
		// Parameters named like the builder variable, the strings package
		// and the builtin len.
		Spec{FuncName: "Names", Template: "{b}/{strings}/{len}/{len_}"},
		// A top-level name that takes "strings", so the import needs an alias.
		Spec{FuncName: "strings", Template: "pkg"},
	)
	if err != nil {
		t.Fatal(err)
	}

	mainSrc := `package main

import "fmt"

func main() {
	fmt.Println(Greet("gopher", "Go"))
	fmt.Println(Empty() == "")
	fmt.Println(Static())
	fmt.Println(Only("v"))
	fmt.Println(Repeat("1", "2"))
	fmt.Println(Braces("key", "val"))
	fmt.Println(Clash("X"))
	fmt.Println(Names("1", "2", "3", "4"))
	fmt.Println(strings())
}
`
	want := strings.Join([]string{
		"Hello gopher, welcome to Go!",
		"true",
		"no placeholders",
		"v",
		"1-1-2",
		`{"key": "val"}`,
		"aXb",
		"1/2/3/4",
		"pkg",
	}, "\n") + "\n"

	dir := t.TempDir()
	write := func(name, content string) {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("go.mod", "module gentest\n\ngo 1.26\n")
	write("gen.go", string(src))
	write("main.go", mainSrc)

	cmd := exec.Command("go", "run", ".")
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("go run failed: %v\n%s\ngenerated:\n%s", err, out, src)
	}
	if string(out) != want {
		t.Errorf("output:\n%s\nwant:\n%s", out, want)
	}
}
