package generator

import (
	"os"
	"path/filepath"
	"reflect"
	"strings"
	"testing"
)

func writeFiles(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	for name, src := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

func TestScan(t *testing.T) {
	dir := writeFiles(t, map[string]string{
		"a.go": `package store

// Queries for users.

//qfiller:QUser SELECT * FROM {schema}.users WHERE id = {id}

//qfiller:QJoin
// SELECT *
// FROM {schema}.users u
//   INNER JOIN {schema}.store s ON s.user_id = u.id
//qfiller:QCount SELECT count(*) FROM {schema}.users

/*qfiller:QBlock
SELECT {col}
FROM t
*/

// Ordinary comment, ignored.
func x() {}
`,
		"b.go": `package store

/*qfiller:QInline SELECT 1 */
`,
		"b_test.go": `package store

//qfiller:QTest SELECT 2
`,
		"gen.go": `// Code generated by qfiller. DO NOT EDIT.

package store

//qfiller:QGen SELECT 3
`,
	})

	pkg, specs, err := Scan(dir)
	if err != nil {
		t.Fatal(err)
	}
	if pkg != "store" {
		t.Errorf("pkg = %q, want store", pkg)
	}
	want := []Spec{
		{FuncName: "QUser", Template: "SELECT * FROM {schema}.users WHERE id = {id}"},
		{FuncName: "QJoin", Template: "SELECT *\nFROM {schema}.users u\n  INNER JOIN {schema}.store s ON s.user_id = u.id"},
		{FuncName: "QCount", Template: "SELECT count(*) FROM {schema}.users"},
		{FuncName: "QBlock", Template: "SELECT {col}\nFROM t"},
		{FuncName: "QInline", Template: "SELECT 1"},
	}
	if !reflect.DeepEqual(specs, want) {
		t.Errorf("specs:\n got %#v\nwant %#v", specs, want)
	}

	if _, err := Generate(pkg, specs...); err != nil {
		t.Fatalf("Generate: %v", err)
	}
}

func TestScanErrors(t *testing.T) {
	tests := map[string]string{
		"no name":        "//qfiller: SELECT 1\n",
		"bad name":       "//qfiller:1abc SELECT 1\n",
		"no template":    "//qfiller:Q\n",
		"bad template":   "//qfiller:Q SELECT {x\n",
		"doc comment":    "// Q does things.\n//\n//qfiller:Q\nfunc Q() {}\n",
		"duplicate name": "//qfiller:Q SELECT 1\n\n//qfiller:Q SELECT 2\n",
	}
	for name, body := range tests {
		t.Run(name, func(t *testing.T) {
			dir := writeFiles(t, map[string]string{"a.go": "package p\n\n" + body})
			_, _, err := Scan(dir)
			if err == nil {
				t.Fatal("expected error")
			}
			if !strings.Contains(err.Error(), "a.go:") {
				t.Errorf("error %q has no source position", err)
			}
		})
	}
}

func TestScanPackageMismatch(t *testing.T) {
	dir := writeFiles(t, map[string]string{
		"a.go": "package a\n",
		"b.go": "package b\n",
	})
	if _, _, err := Scan(dir); err == nil {
		t.Fatal("expected error")
	}
}
