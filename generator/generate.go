package generator

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/token"
	"strconv"
	"unicode"
	"unicode/utf8"
)

// Spec describes one function to generate from a template.
type Spec struct {
	FuncName string // name of the generated function
	Template string // template text, e.g. "Hello {name}!"
}

// Generate builds a Go source file in package pkg with one function per spec.
// Each function takes the template's placeholders as string parameters, in
// order of first appearance, and returns the filled string. A placeholder
// used more than once maps to a single parameter.
func Generate(pkg string, specs ...Spec) ([]byte, error) {
	if !token.IsIdentifier(pkg) || token.IsKeyword(pkg) {
		return nil, fmt.Errorf("invalid package name %q", pkg)
	}

	// Function names are top-level, so collect them first so that the
	// literal constant names never clash with them.
	used := map[string]bool{}
	for _, s := range specs {
		if !token.IsIdentifier(s.FuncName) || token.IsKeyword(s.FuncName) {
			return nil, fmt.Errorf("invalid function name %q", s.FuncName)
		}
		if used[s.FuncName] {
			return nil, fmt.Errorf("duplicate function name %q", s.FuncName)
		}
		used[s.FuncName] = true
	}

	file := &ast.File{Name: ast.NewIdent(pkg)}
	for _, s := range specs {
		parts, err := Parse(s.Template)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", s.FuncName, err)
		}
		consts, fn := buildFunc(s.FuncName, parts, used)
		if consts != nil {
			file.Decls = append(file.Decls, consts)
		}
		file.Decls = append(file.Decls, fn)
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by qfiller. DO NOT EDIT.\n\n")
	if err := format.Node(&buf, token.NewFileSet(), file); err != nil {
		return nil, fmt.Errorf("format: %w", err)
	}
	return buf.Bytes(), nil
}

// buildFunc returns the const block for the literal parts (nil if there are
// none) and the function declaration that joins all parts in order.
// used holds top-level names already taken and is updated with new ones.
func buildFunc(funcName string, parts []Part, used map[string]bool) (*ast.GenDecl, *ast.FuncDecl) {
	// Parameters: one per distinct placeholder, in order of first use.
	var params []*ast.Ident
	seen := map[string]bool{}
	for _, p := range parts {
		if p.Kind == Variadic && !seen[p.Value] {
			seen[p.Value] = true
			params = append(params, ast.NewIdent(p.Value))
		}
	}

	// A constant must not be shadowed by a parameter in the function body.
	taken := func(name string) bool { return used[name] || seen[name] }

	var specs []ast.Spec
	var operands []ast.Expr
	prefix := lowerFirst(funcName) + "Lit"
	for _, p := range parts {
		switch p.Kind {
		case Literal:
			name := uniqueName(prefix+strconv.Itoa(len(specs)), taken)
			used[name] = true
			specs = append(specs, &ast.ValueSpec{
				Names:  []*ast.Ident{ast.NewIdent(name)},
				Values: []ast.Expr{&ast.BasicLit{Kind: token.STRING, Value: strconv.Quote(p.Value)}},
			})
			operands = append(operands, ast.NewIdent(name))
		case Variadic:
			operands = append(operands, ast.NewIdent(p.Value))
		}
	}

	var result ast.Expr = &ast.BasicLit{Kind: token.STRING, Value: `""`}
	if len(operands) > 0 {
		result = operands[0]
		for _, op := range operands[1:] {
			result = &ast.BinaryExpr{X: result, Op: token.ADD, Y: op}
		}
	}

	var paramList []*ast.Field
	if len(params) > 0 {
		paramList = []*ast.Field{{Names: params, Type: ast.NewIdent("string")}}
	}

	fn := &ast.FuncDecl{
		Name: ast.NewIdent(funcName),
		Type: &ast.FuncType{
			Params:  &ast.FieldList{List: paramList},
			Results: &ast.FieldList{List: []*ast.Field{{Type: ast.NewIdent("string")}}},
		},
		Body: &ast.BlockStmt{List: []ast.Stmt{
			&ast.ReturnStmt{Results: []ast.Expr{result}},
		}},
	}

	if len(specs) == 0 {
		return nil, fn
	}
	consts := &ast.GenDecl{Tok: token.CONST, Specs: specs}
	if len(specs) > 1 {
		consts.Lparen = 1 // non-zero position makes the printer use a ( ... ) block
	}
	return consts, fn
}

func uniqueName(name string, taken func(string) bool) string {
	for taken(name) {
		name += "_"
	}
	return name
}

func lowerFirst(s string) string {
	r, n := utf8.DecodeRuneInString(s)
	return string(unicode.ToLower(r)) + s[n:]
}
